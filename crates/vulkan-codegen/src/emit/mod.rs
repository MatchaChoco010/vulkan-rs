//! Source emitters. Each returns unformatted Rust; `tools/generate-vulkan` runs rustfmt.

pub mod basic;
pub mod commands;
pub mod layout;
pub mod structs;

/// `writeln!` into a `String`, which cannot fail.
macro_rules! w {
    ($out:expr, $($arg:tt)*) => {{
        use std::fmt::Write as _;
        writeln!($out, $($arg)*).expect("write to String")
    }};
}
pub(crate) use w;

/// File header shared by all generated modules.
pub fn header(clippy_allows: &[&str]) -> String {
    let mut out = String::from("// @generated by vulkan-codegen. Do not edit.\n\n");
    for lint in [
        "non_camel_case_types",
        "non_snake_case",
        "non_upper_case_globals",
        "unused_imports",
    ] {
        w!(out, "#![allow({lint})]");
    }
    for lint in clippy_allows {
        w!(out, "#![allow(clippy::{lint})]");
    }
    out.push_str("\nuse crate::vk::*;\n\n");
    out
}
